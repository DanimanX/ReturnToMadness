    candle(False).save(os.path.join(outdir, "ui_candle_empty.png"))
    eye_icon().save(os.path.join(outdir, "ui_eye.png"))
    title().save(os.path.join(outdir, "title.png"))
    print("ui: font, candles, eye, title")


