# --------------------------------------------------------------- acentos
# Las cinco lenguas necesitan: á é í ó ú à è ì ò ù â ê î ô û ã õ ç ñ ü ë ï
# y las comillas latinas «». El glifo base ocupa las filas 2..8; las filas
# 0..1 son para el acento y la 9 para la cedilla.
ACCENTS = {
	"Á": ("A", "acute"), "É": ("E", "acute"), "Í": ("I", "acute"),
	"Ó": ("O", "acute"), "Ú": ("U", "acute"),
	"À": ("A", "grave"), "È": ("E", "grave"), "Ì": ("I", "grave"),
	"Ò": ("O", "grave"), "Ù": ("U", "grave"),
	"Â": ("A", "circ"), "Ê": ("E", "circ"), "Î": ("I", "circ"),
	"Ô": ("O", "circ"), "Û": ("U", "circ"),
	"Ã": ("A", "tilde"), "Ñ": ("N", "tilde"), "Õ": ("O", "tilde"),
	"Ä": ("A", "diaer"), "Ë": ("E", "diaer"), "Ï": ("I", "diaer"),
	"Ö": ("O", "diaer"), "Ü": ("U", "diaer"), "Ÿ": ("Y", "diaer"),
	"Ç": ("C", "cedil"),
}

MARKS = {
	"acute": [(2, 0), (3, 1)],
	"grave": [(3, 0), (2, 1)],
	"circ":  [(2, 0), (1, 1), (3, 1)],
	"tilde": [(1, 0), (2, 0), (3, 0), (0, 1), (4, 1)],
	"diaer": [(1, 0), (3, 0)],
}


def render_glyph(ch, color=(214, 206, 184, 255)):
	cell = Image.new("RGBA", (CELL_W, CELL_H), (0, 0, 0, 0))
	if ch == " ":
		return cell
	base = ch
	accent = None
	if ch in ACCENTS:
		base, accent = ACCENTS[ch]
	rows = G.get(base)
	if rows is None:
		# carácter desconocido: se dibuja un hueco, nunca se rompe el texto
		return cell
	for y, row in enumerate(rows):
		for x, c in enumerate(row):
			if c == "#":
				cell.putpixel((x, y + 2), color)
	if accent in MARKS:
		for (x, y) in MARKS[accent]:
			cell.putpixel((x, y), color)
	elif accent == "cedil":
		cell.putpixel((2, 9), color)
		cell.putpixel((1, 9), color)
	return cell


